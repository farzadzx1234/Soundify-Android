export type TranslationKey = keyof typeof TRANSLATIONS.en;

interface I18nContextValue {
  lang: Lang;
  dir: "rtl" | "ltr";
  setLang: (lang: Lang) => void;
  toggleLang: () => void;
  t: (key: TranslationKey) => string;
  pickText: (en: string, fa?: string | null) => string;
  formatNum: (num: number) => string;
}

const I18nContext = createContext<I18nContextValue | null>(null);

const LANG_EVENT = "soundify-lang-change";

function subscribeLang(cb: () => void): () => void {
  const onStorage = (e: StorageEvent) => {
    if (e.key === "soundify_lang") cb();
  };
  window.addEventListener("storage", onStorage);
  window.addEventListener(LANG_EVENT, cb);
  return () => {
    window.removeEventListener("storage", onStorage);
    window.removeEventListener(LANG_EVENT, cb);
  };
}

function getLangSnapshot(): Lang {
  try {
    const saved = localStorage.getItem("soundify_lang");
    if (saved === "en" || saved === "fa") return saved;
  } catch {
    // ignore
  }
  return "fa";
}

function getLangServerSnapshot(): Lang {
  return "fa";
}

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const lang = useSyncExternalStore(subscribeLang, getLangSnapshot, getLangServerSnapshot);

  useLayoutEffect(() => {
    const dir = lang === "fa" ? "rtl" : "ltr";
    document.documentElement.lang = lang;
    document.documentElement.dir = dir;
  }, [lang]);

  const setLang = useCallback((next: Lang) => {
    try {
      localStorage.setItem("soundify_lang", next);
    } catch {
      // ignore
    }
    if (typeof document !== "undefined") {
      document.documentElement.lang = next;
      document.documentElement.dir = next === "fa" ? "rtl" : "ltr";
    }
    window.dispatchEvent(new Event(LANG_EVENT));
  }, []);

  const toggleLang = useCallback(() => {
    setLang(getLangSnapshot() === "fa" ? "en" : "fa");
  }, [setLang]);

  const t = useCallback((key: TranslationKey) => TRANSLATIONS[lang][key], [lang]);

  const pickText = useCallback(
    (en: string, fa?: string | null) => (lang === "fa" && fa && fa.trim() ? fa : en),
    [lang],
  );

  const formatNum = useCallback(
    (num: number) => {
      try {
        return new Intl.NumberFormat(lang === "fa" ? "fa-IR" : "en-US").format(num);
      } catch {
        return String(num);
      }
    },
    [lang],
  );

  const value = useMemo<I18nContextValue>(
    () => ({
      lang,
      dir: lang === "fa" ? "rtl" : "ltr",
      setLang,
      toggleLang,
      t,
      pickText,
      formatNum,
    }),
    [lang, setLang, toggleLang, t, pickText, formatNum],
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n must be used inside I18nProvider");
  return ctx;
}
