function generatePeaks(seed: number): number[] {
  const peaks: number[] = [];
  for (let i = 0; i < 64; i++) {
    const val = Math.abs(Math.sin((i + seed * 7) * 0.28) * 0.7 + Math.cos((i + seed * 3) * 0.44) * 0.3);
    peaks.push(Math.round(Math.max(0.12, Math.min(1.0, val)) * 100) / 100);
  }
  return peaks;
}

