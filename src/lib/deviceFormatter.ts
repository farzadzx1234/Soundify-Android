export function localizeDeviceName(name: string, lang: "fa" | "en"): string {
  if (!name || typeof name !== "string") {
    return lang === "fa" ? "دستگاه راه دور" : "Remote Device";
  }

  const trimmed = name.trim();
  if (!trimmed) {
    return lang === "fa" ? "دستگاه راه دور" : "Remote Device";
  }

  if (lang === "en") {
    // Exact mapping for Persian device names
    if (FA_TO_EN_DEVICE_MAP[trimmed]) {
      return FA_TO_EN_DEVICE_MAP[trimmed];
    }
    if (trimmed.includes("دیوایس دیگر") || trimmed.includes("دستگاه راه دور")) {
      return "Remote Device";
    }

    // Check for `${faBrowser} در ${faOs}` pattern
    const faMatch = trimmed.match(/^(.+?)\s+در\s+(.+)$/);
    if (faMatch) {
      const rawFaBrowser = faMatch[1].trim();
      const rawFaOs = faMatch[2].trim();
      const enBrowser = BROWSER_MAP_FA_TO_EN[rawFaBrowser] || rawFaBrowser;
      const enOs = OS_MAP_FA_TO_EN[rawFaOs] || rawFaOs;
      return `${enBrowser} on ${enOs}`;
    }

    return trimmed;
  }

  // Persian translation mode
  const lower = trimmed.toLowerCase();

  // Exact dictionary match
  if (EN_TO_FA_DEVICE_MAP[lower]) {
    return EN_TO_FA_DEVICE_MAP[lower];
  }

  if (
    trimmed.includes("دیوایس دیگر") ||
    lower.includes("remote device")
  ) {
    return "دستگاه راه دور";
  }

  // Check for `${browser} on ${os}` pattern generated by detectDeviceName()
  const onMatch = trimmed.match(/^(.+?)\s+on\s+(.+)$/i);
  if (onMatch) {
    const rawBrowser = onMatch[1].trim();
    const rawOs = onMatch[2].trim();

    const faBrowser = BROWSER_MAP_EN_TO_FA[rawBrowser.toLowerCase()] || rawBrowser;
    const faOs = OS_MAP_EN_TO_FA[rawOs.toLowerCase()] || rawOs;
    return `${faBrowser} در ${faOs}`;
  }

  return trimmed;
}

export function getDeviceTypeLabel(
  type: "desktop" | "smartphone" | "tablet" | "browser" | "speaker" | string,
  t: (k: TranslationKey) => string,
): string {
  switch (type) {
    case "desktop":
      return t("deviceTypeDesktop");
    case "smartphone":
      return t("deviceTypeSmartphone");
    case "tablet":
      return t("deviceTypeTablet");
    case "browser":
      return t("deviceTypeBrowser");
    case "speaker":
      return t("deviceTypeSpeaker");
    default:
      return t("deviceTypeUnknown");
  }
}

